export function formatPubDate(dateStr) {
	return new Date(dateStr + 'T00:00:00').toLocaleDateString('en-GB', {
		day: 'numeric',
		month: 'long',
		year: 'numeric',
	});
}

export function formatPubDateShort(dateStr) {
	return new Date(dateStr + 'T00:00:00').toLocaleDateString('en-GB', {
		month: 'short',
		year: 'numeric',
	});
}

// Short badge label for an indexing tier.
export function indexingBadge(indexing) {
	if (indexing.startsWith('SCIE / ISI')) return indexing.replace('SCIE / ISI ', '');
	if (indexing === 'Scopus Q3') return 'Scopus';
	if (indexing === 'International Conference') return 'Conference';
	if (indexing === 'National Journal (KSA)') return 'National';
	return 'Non-ISI';
}
